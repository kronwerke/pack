#!/usr/bin/env python3
"""Adds mods from Modrinth to the pack as packwiz files, without packwiz.

  addmod.py [--dry] [--update] <slug>[:client|:server|:both] ...

Takes the newest release for NeoForge 1.21.1 (a beta only when there is no release), writes
mods/<slug>.pw.toml, and says which required dependencies are not in the pack yet. The side
With --update a mod that is in the pack already is moved to that newest version (its file is
found by the Modrinth id, the side it has is kept). The side of a new mod
comes from Modrinth unless given: client when the server does not support the mod, both
otherwise (so a singleplayer world behaves like the server). The index is regenerated by CI.
"""
import glob
import json
import os
import re
import sys
import urllib.parse
import urllib.request

API = "https://api.modrinth.com/v2"
UA = "kronwerke-pack-tools/0.1 (github.com/kronwerke/pack)"
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def get(path):
    req = urllib.request.Request(API + path, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def in_pack():
    ids = {}
    for f in glob.glob(os.path.join(root, "mods", "*.pw.toml")):
        m = re.search(r'mod-id = "([^"]+)"', open(f, encoding="utf-8").read())
        if m:
            ids[m.group(1)] = os.path.basename(f)
    return ids


def main():
    args = [a for a in sys.argv[1:] if a not in ("--dry", "--update")]
    dry = "--dry" in sys.argv
    update = "--update" in sys.argv
    have = in_pack()
    for arg in args:
        slug, _, side = arg.partition(":")
        p = get("/project/" + slug)
        q = urllib.parse.urlencode({"loaders": '["neoforge"]', "game_versions": '["1.21.1"]'})
        versions = get(f"/project/{slug}/version?{q}")
        if not versions:
            print(f"{slug}: NO version for NeoForge 1.21.1")
            continue
        releases = [v for v in versions if v["version_type"] == "release"]
        v = (releases or versions)[0]
        file = next((f for f in v["files"] if f["primary"]), v["files"][0])
        if not side:
            side = "client" if p["server_side"] == "unsupported" else "both"
        deps = []
        for d in v["dependencies"]:
            if d["dependency_type"] != "required" or not d.get("project_id"):
                continue
            if d["project_id"] in have:
                continue
            deps.append(get("/project/" + d["project_id"])["slug"])
        state = "already in the pack" if p["id"] in have else "new"
        print(f"{slug}: {p['title']} {v['version_number']} ({v['version_type']}, {v['date_published'][:10]}), side {side}, {state}"
              + (f", NEEDS {', '.join(deps)}" if deps else ""))
        if dry or (p["id"] in have and not update):
            continue
        target = os.path.join(root, "mods", have.get(p["id"], slug + ".pw.toml"))
        if p["id"] in have:
            old = open(target, encoding="utf-8").read()
            side = re.search(r'side = "([^"]+)"', old).group(1)
            if f'version = "{v["id"]}"' in old:
                continue
        text = (f'name = "{p["title"]}"\nfilename = "{file["filename"]}"\nside = "{side}"\n\n[download]\n'
                f'url = "{file["url"]}"\nhash-format = "sha512"\nhash = "{file["hashes"]["sha512"]}"\n\n'
                f'[update]\n[update.modrinth]\nmod-id = "{p["id"]}"\nversion = "{v["id"]}"\n')
        with open(target, "w", encoding="utf-8") as f:
            f.write(text)


if __name__ == "__main__":
    main()
